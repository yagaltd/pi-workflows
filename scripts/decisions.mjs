#!/usr/bin/env node
// decisions — the standing decision index (plan 20261025-027).
// One short record per standing decision under .workflows/decisions/;
// INDEX.md is generated, never hand-edited; `adr: DEC-NNN` references in the
// live plan must resolve. Zero dependencies.
//
// Usage:
//   node scripts/decisions.mjs record --id DEC-001 --title "..." --rule "..." \
//        --scope "scripts/**" --decided-by <planId> --revisit "<condition>" \
//        [--dir .workflows/decisions] [--status active]
//   node scripts/decisions.mjs supersede --id DEC-001 --by DEC-002 --reason "<why>" [--dir ...]
//   node scripts/decisions.mjs list [--dir ...]
//   node scripts/decisions.mjs index [--dir ...]            (regenerate INDEX.md)
//   node scripts/decisions.mjs check [--plan .workflows/plan.md] [--dir ...]
// Exit: check 0 ok / 1 findings · record/supersede/index 0 · 2 usage.

import fs from "node:fs";
import path from "node:path";

const REQUIRED = ["Status", "Decided-by", "Scope", "Revisit when"];

export function parseArgs(argv) {
  const o = { cmd: null, dir: ".workflows/decisions", plan: ".workflows/plan.md", status: "active", by: null, reason: null };
  const keys = ["id", "title", "rule", "scope", "decided-by", "revisit", "by", "reason"];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "record" || a === "supersede" || a === "list" || a === "index" || a === "check") o.cmd = a;
    else if (a === "--dir") o.dir = argv[++i];
    else if (a === "--plan") o.plan = argv[++i];
    else if (a === "--status") o.status = argv[++i];
    else if (a === "--reason") o.reason = argv[++i];
    else if (a.startsWith("--")) {
      const key = a.slice(2);
      if (!keys.includes(key)) return { error: `unknown argument: ${a}` };
      o[key.replace(/-([a-z])/g, (_, c) => c.toUpperCase())] = argv[++i];
    } else return { error: `unknown argument: ${a}` };
  }
  if (!o.cmd) return { error: "subcommand required: record | supersede | list | index | check" };
  if (o.cmd === "record" && (!o.id || !o.title || !o.rule || !o.scope || !o.decidedBy || !o.revisit))
    return { error: "record needs --id --title --rule --scope --decided-by --revisit" };
  if (o.cmd === "supersede" && (!o.id || !o.by || !o.reason)) return { error: "supersede needs --id --by --reason" };
  return { opts: o };
}

const slug = (title) => title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 40);
const recordFile = (dir, id) => path.join(dir, `${id}.md`);

export function writeRecord(dir, { id, title, rule, scope, decidedBy, revisit, status = "active" }) {
  fs.mkdirSync(dir, { recursive: true });
  const text = `# ${id}: ${title}

> Status: ${status}
> Decided-by: ${decidedBy}
> Scope: ${scope}
> Revisit when: ${revisit}

Rule: ${rule}
`;
  fs.writeFileSync(recordFile(dir, id), text);
  regenerateIndex(dir);
}

export function parseRecord(text, file) {
  const field = (name) => {
    const m = new RegExp(`^> ${name}: (.+)$`, "m").exec(text);
    return m ? m[1].trim() : null;
  };
  const id = ( /^# (DEC-\d+):/m.exec(text) || [] )[1] ?? null;
  const rule = /^Rule: (.+)$/m.exec(text);
  const rec = {
    file,
    id,
    title: id ? text.split("\n")[0].replace(`# ${id}: `, "") : null,
    status: field("Status"),
    decidedBy: field("Decided-by"),
    scope: field("Scope"),
    revisit: field("Revisit when"),
    rule: rule ? rule[1].trim() : null,
  };
  return rec;
}

export function loadRecords(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((f) => /^DEC-\d+.*\.md$/.test(f))
    .map((f) => parseRecord(fs.readFileSync(path.join(dir, f), "utf8"), f))
    .sort((a, b) => (a.id ?? "").localeCompare(b.id ?? ""));
}

export function renderIndex(records) {
  const lines = ["# Decision index", "", "Generated by `scripts/decisions.mjs index` — never hand-edit.", ""];
  for (const r of records) {
    lines.push(`- **${r.id}** ${r.title ?? "(untitled)"} — ${r.status ?? "?"} · decided-by \`${r.decidedBy ?? "?"}\` · scope: ${r.scope ?? "?"}`);
    if (r.status && r.status.startsWith("superseded")) lines.push(`  superseded: ${r.status}`);
    lines.push(`  rule: ${r.rule ?? "?"}`);
    lines.push(`  revisit when: ${r.revisit ?? "?"}`);
  }
  return lines.join("\n") + "\n";
}

export function regenerateIndex(dir) {
  fs.writeFileSync(path.join(dir, "INDEX.md"), renderIndex(loadRecords(dir)));
}

export function supersede(dir, { id, by, reason }) {
  const file = recordFile(dir, id);
  if (!fs.existsSync(file)) return { ok: false, reason: `unknown record: ${id}` };
  if (!fs.existsSync(recordFile(dir, by))) return { ok: false, reason: `successor record missing: ${by}` };
  let text = fs.readFileSync(file, "utf8");
  text = text.replace("> Status: active", `> Status: superseded (by ${by} — ${reason})`);
  if (!text.includes("> Status: superseded")) return { ok: false, reason: `${id} is not active` };
  fs.writeFileSync(file, text);
  regenerateIndex(dir);
  return { ok: true };
}

export function adrRefs(planText) {
  const out = [];
  const re = /adr:?\s*(DEC-\d+)/g;
  let m;
  while ((m = re.exec(planText)) !== null) out.push(m[1]);
  return out;
}

const FIELD_KEYS = { "Status": "status", "Decided-by": "decidedBy", "Scope": "scope", "Revisit when": "revisit" };

export function check({ dir, plan }) {
  const findings = [];
  const records = loadRecords(dir);
  const ids = new Set(records.map((r) => r.id).filter(Boolean));
  for (const r of records) {
    for (const f of REQUIRED) {
      if (!r[FIELD_KEYS[f]]) findings.push(`${r.file}: missing field "${f}"`);
    }
    if (!r.rule) findings.push(`${r.file}: missing Rule line`);
    if (r.status && r.status.startsWith("superseded")) {
      const succ = /\(by (DEC-\d+)/.exec(r.status);
      if (succ && !ids.has(succ[1])) findings.push(`${r.file}: superseded by unknown ${succ[1]}`);
    }
  }
  const planText = fs.existsSync(plan) ? fs.readFileSync(plan, "utf8") : "";
  for (const ref of adrRefs(planText)) {
    if (!ids.has(ref)) findings.push(`live plan references unresolved ${ref}`);
  }
  const indexFile = path.join(dir, "INDEX.md");
  const expected = renderIndex(records);
  if (fs.existsSync(indexFile) && fs.readFileSync(indexFile, "utf8") !== expected) {
    findings.push("INDEX.md drifted from regeneration — run: node scripts/decisions.mjs index");
  }
  return { ok: findings.length === 0, findings, records };
}

export async function main(argv) {
  const { opts, error } = parseArgs(argv);
  if (error) { console.error(`usage error: ${error}`); return 2; }
  fs.mkdirSync(opts.dir, { recursive: true });

  if (opts.cmd === "record") {
    writeRecord(opts.dir, { ...opts, status: opts.status ?? "active" });
    console.log(`recorded ${opts.id} → ${recordFile(opts.dir, opts.id)}`);
    return 0;
  }
  if (opts.cmd === "supersede") {
    const r = supersede(opts.dir, opts);
    console.log(r.ok ? `superseded ${opts.id} → ${opts.by}` : `refused: ${r.reason}`);
    return r.ok ? 0 : 1;
  }
  if (opts.cmd === "list") {
    for (const r of loadRecords(opts.dir)) console.log(`${r.id} [${r.status}] ${r.title} — revisit: ${r.revisit}`);
    return 0;
  }
  if (opts.cmd === "index") {
    regenerateIndex(opts.dir);
    console.log(`INDEX.md regenerated (${loadRecords(opts.dir).length} records)`);
    return 0;
  }
  if (opts.cmd === "check") {
    const { ok, findings } = check({ dir: opts.dir, plan: opts.plan });
    for (const f of findings) console.error(`FINDING: ${f}`);
    console.log(`decisions check: ${ok ? "CLEAN" : `${findings.length} finding(s)`} · ${loadRecords(opts.dir).length} record(s)`);
    return ok ? 0 : 1;
  }
  return 2;
}

if (import.meta.url === `file://${process.argv[1]}`) main(process.argv.slice(2)).then((code) => process.exit(code));
